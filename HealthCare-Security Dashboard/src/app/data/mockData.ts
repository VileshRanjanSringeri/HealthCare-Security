export const generateVitalSignsHistory = (baseValue: number, variance: number, points: number = 24) => {
  return Array.from({ length: points }, (_, i) => ({
    time: `${23 - i}:00`,
    value: Math.round(baseValue + (Math.random() - 0.5) * variance),
  })).reverse();
};

